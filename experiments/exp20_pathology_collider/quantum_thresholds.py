# GA-only params (not optimized by QAOA — keep existing defaults)
GA_ONLY_DEFAULTS: dict[str, Any] = {
    "token_velocity":     2000,   # L2 PathologyTensor threshold (int)
    "suspicion_window":   3,      # PathologyBridge suspicion window (int)
    "burst_threshold":    2,      # L3 InsertionMonitor burst detector (int)
    "corruption_ceiling": 0.3,    # L3 InsertionMonitor ceiling (float)
}


# ═══════════════════════════════════════════════════════════════════════════
# Configuration helpers
# ═══════════════════════════════════════════════════════════════════════════

def get_defense_config() -> dict[str, Any]:
    """
    Return the full defense configuration merging quantum-optimized
    and GA-default parameters.

    Returns:
        dict with all 16 threshold values needed by defense_layers.py
    """
    return {**QUANTUM_THRESHOLDS, **GA_ONLY_DEFAULTS}


def get_layer_config(layer: str) -> dict[str, Any]:
    """
    Return thresholds for a specific defense layer.

    Args:
        layer: One of 'telemetry', 'tensor', 'memory', 'economic'
    """
    cfg = get_defense_config()

    if layer == "telemetry":
        return {
            "scan_probability": cfg["scan_probability"],
            "sentinel_sensitivity": cfg["sentinel_sensitivity"],
            "manipulation_threshold": cfg["manipulation_threshold"],
        }
    elif layer == "tensor":
        return {
            "compound_threshold": int(round(cfg["compound_threshold"])),
            "token_velocity": cfg["token_velocity"],
            "alert_cooldown": cfg["alert_cooldown"],
        }
    elif layer == "memory":
        return {
            "trust_threshold": cfg["trust_threshold"],
            "min_trust_floor": cfg["min_trust_floor"],
            "memory_decay_rate": cfg["memory_decay_rate"],
            "burst_threshold": cfg["burst_threshold"],
            "corruption_ceiling": cfg["corruption_ceiling"],
            "drift_threshold": cfg["drift_threshold"],
        }
    elif layer == "economic":
        return {
            "spike_threshold": cfg["spike_threshold"],
            "burn_rate_accel": cfg["burn_rate_accel"],
            "token_budget_margin": cfg["token_budget_margin"],
        }
    else:
        raise ValueError(f"Unknown layer: {layer}")


def load_from_file(path: str | Path) -> dict[str, float]:
    """Load thresholds from a JSON config file (e.g. from Phase 1 export)."""
    with open(path) as f:
        data = json.load(f)
    if "thresholds" in data:
        return data["thresholds"]
    return data


# GA genome compatibility
def to_ga_genome() -> dict[str, float]:
    """
    Convert QAOA thresholds to GA Genome.genes format.

    Maps the 8 shared params directly and includes GA-only params
    at their defaults.  Used by Genome.from_qaoa().
    """
    genome_genes: dict[str, float] = {}

    # Shared params (direct map)
    for name in [
        "trust_threshold", "scan_probability", "compound_threshold",
        "spike_threshold", "drift_threshold", "min_trust_floor",
        "manipulation_threshold", "burn_rate_accel",
    ]:
        val = QUANTUM_THRESHOLDS[name]
        # GA expects int for compound_threshold
        if name == "compound_threshold":
            val = int(round(val))
        genome_genes[name] = val

    # GA-only params
    genome_genes.update(GA_ONLY_DEFAULTS)

    return genome_genes
