"""
Sync Public Repo — Incrementally update the public-facing repository.

Unlike export_public_repo.py (which destroys and re-generates), this script
**preserves** the public repo's git history and only updates files that
have actually changed.

What it syncs:
  ✅ Redacted AVE cards (JSON + Markdown) — stripped of mechanism/PoC/evidence
  ✅ Database indexes (index.json, severity_index.json)
  ✅ Lightweight AVE toolkit modules (safe subset)
  ✅ Community docs (CONTRIBUTING, CODE_OF_CONDUCT, SECURITY)
  ✅ GitHub infrastructure (.github/ templates, workflows)

What it NEVER syncs:
  ❌ Full enriched cards (mechanism, evidence, PoC, AVSS vectors)
  ❌ Commercial packages (rmap, canary, arena, ctf, threatfeed)
  ❌ Docker infrastructure, experiment data, research papers
  ❌ HALL_OF_FAME.md (auto-generated by GitHub Actions)

Usage:
    python scripts/sync_public_repo.py                  # Dry-run (preview)
    python scripts/sync_public_repo.py --apply          # Apply changes
    python scripts/sync_public_repo.py --apply --commit # Apply + git commit
"""

