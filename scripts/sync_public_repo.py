def _rewrite_urls(text: str) -> str:
    """Replace all private repo references with the public org URL."""
    for slug in PRIVATE_SLUGS:
        text = text.replace(slug, PUBLIC_SLUG)
    return text


def _files_differ(src: Path, dst: Path) -> bool:
    """Check if two files have different content."""
    if not dst.exists():
        return True
    if not src.exists():
        return False
    return not filecmp.cmp(str(src), str(dst), shallow=False)


def _write_if_changed(content: str, dst: Path, stats: dict) -> bool:
    """Write content to dst only if it differs. Returns True if written."""
    if dst.exists() and dst.read_text() == content:
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(content)
    stats["updated"] += 1
    return True


class SyncReport:
    """Tracks what changed during sync."""

    def __init__(self):
        self.updated: list[str] = []
        self.added: list[str] = []
        self.unchanged: list[str] = []
        self.skipped: list[str] = []
        self.errors: list[str] = []

    def add(self, path: str, status: str):
        getattr(self, status, self.skipped).append(path)

    def summary(self) -> str:
        lines = [
            f"\n{'═' * 60}",
            f"  Sync Report",
            f"{'═' * 60}",
            f"  Added:     {len(self.added)}",
            f"  Updated:   {len(self.updated)}",
            f"  Unchanged: {len(self.unchanged)}",
            f"  Skipped:   {len(self.skipped)}",
            f"  Errors:    {len(self.errors)}",
        ]
        if self.added:
            lines.append(f"\n  ➕ Added:")
            for p in self.added:
                lines.append(f"     {p}")
        if self.updated:
            lines.append(f"\n  🔄 Updated:")
            for p in self.updated:
                lines.append(f"     {p}")
        if self.errors:
            lines.append(f"\n  ❌ Errors:")
            for p in self.errors:
                lines.append(f"     {p}")
        lines.append(f"{'═' * 60}")
        return "\n".join(lines)

    @property
    def has_changes(self) -> bool:
        return bool(self.added or self.updated)


def sync_cards(
    source_root: Path,
    public_root: Path,
    report: SyncReport,
    dry_run: bool = True,
) -> int:
    """Sync redacted AVE cards from private → public."""
    cards_src = source_root / "ave-database" / "cards"
    cards_dst = public_root / "ave-database" / "cards"
    cards_dst.mkdir(parents=True, exist_ok=True)

    count = 0
    for card_file in sorted(cards_src.glob("AVE-*.json")):
        try:
            with open(card_file) as f:
                full_card = json.load(f)

            # Redact to public tier
            public_card = redact_card(full_card, "public")

            # Rewrite internal URLs
            card_json = json.dumps(public_card, indent=2)
            card_json = _rewrite_urls(card_json)
            public_card = json.loads(card_json)

            # Generate markdown companion
            md_content = generate_public_markdown(public_card)
            md_content = _rewrite_urls(md_content)

            # Check JSON
            json_dst = cards_dst / card_file.name
            new_json = json.dumps(public_card, indent=2) + "\n"
            json_path = f"ave-database/cards/{card_file.name}"

            if json_dst.exists():
                if json_dst.read_text() != new_json:
                    if not dry_run:
                        json_dst.write_text(new_json)
                    report.add(json_path, "updated")
                else:
                    report.add(json_path, "unchanged")
            else:
                if not dry_run:
                    json_dst.write_text(new_json)
                report.add(json_path, "added")

            # Check Markdown
            md_dst = cards_dst / card_file.name.replace(".json", ".md")
            md_path = f"ave-database/cards/{card_file.stem}.md"

            if md_dst.exists():
                if md_dst.read_text() != md_content:
                    if not dry_run:
                        md_dst.write_text(md_content)
                    report.add(md_path, "updated")
                else:
                    report.add(md_path, "unchanged")
            else:
                if not dry_run:
                    md_dst.write_text(md_content)
                report.add(md_path, "added")

            count += 1
        except Exception as e:
            report.add(f"ave-database/cards/{card_file.stem}", "errors")
            print(f"  ✗ {card_file.stem}: {e}")

    return count


def sync_indexes(
    public_root: Path,
    report: SyncReport,
    dry_run: bool = True,
) -> None:
    """Regenerate index.json and severity_index.json from public cards."""
    cards_dir = public_root / "ave-database" / "cards"
    db_dir = public_root / "ave-database"

    cards = []
    for f in sorted(cards_dir.glob("AVE-*.json")):
        with open(f) as fh:
            card = json.load(fh)
            cards.append({
                "ave_id": card.get("ave_id", ""),
                "name": card.get("name", ""),
                "category": card.get("category", ""),
                "severity": card.get("severity", ""),
                "status": card.get("status", ""),
                "summary": card.get("summary", "")[:200],
            })

    # index.json
    index_content = json.dumps({"cards": cards, "total": len(cards)}, indent=2) + "\n"
    index_path = db_dir / "index.json"
    if index_path.exists() and index_path.read_text() == index_content:
        report.add("ave-database/index.json", "unchanged")
    else:
        if not dry_run:
            index_path.write_text(index_content)
        status = "updated" if index_path.exists() else "added"
        report.add("ave-database/index.json", status)

    # severity_index.json
    by_sev: dict[str, list] = {}
    for c in cards:
        sev = c.get("severity", "unknown")
        by_sev.setdefault(sev, []).append(c["ave_id"])
    sev_content = json.dumps(by_sev, indent=2) + "\n"
    sev_path = db_dir / "severity_index.json"
    if sev_path.exists() and sev_path.read_text() == sev_content:
        report.add("ave-database/severity_index.json", "unchanged")
    else:
        if not dry_run:
            sev_path.write_text(sev_content)
        status = "updated" if sev_path.exists() else "added"
        report.add("ave-database/severity_index.json", status)


def sync_toolkit(
    source_root: Path,
    public_root: Path,
    report: SyncReport,
    dry_run: bool = True,
) -> None:
    """Sync safe AVE toolkit modules from private → public."""
    src_dir = source_root / "ave" / "ave"
    dst_dir = public_root / "ave" / "ave"
    dst_dir.mkdir(parents=True, exist_ok=True)

    for fname in PUBLIC_SAFE_MODULES:
        src = src_dir / fname
        if not src.exists():
            report.add(f"ave/ave/{fname}", "skipped")
            continue

        content = src.read_text()
        content = _rewrite_urls(content)

        dst = dst_dir / fname
        rel = f"ave/ave/{fname}"

        if dst.exists():
            if dst.read_text() != content:
                if not dry_run:
                    dst.write_text(content)
                report.add(rel, "updated")
            else:
                report.add(rel, "unchanged")
        else:
            if not dry_run:
                dst.write_text(content)
            report.add(rel, "added")


