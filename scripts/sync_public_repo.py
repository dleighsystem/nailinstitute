def sync_github_infra(
    source_root: Path,
    public_root: Path,
    report: SyncReport,
    dry_run: bool = True,
) -> None:
    """Sync GitHub templates and CI configs."""
    for fpath in GITHUB_FILES:
        src = source_root / fpath
        if not src.exists():
            report.add(fpath, "skipped")
            continue

        content = src.read_text()
        content = _rewrite_urls(content)

        dst = public_root / fpath
        dst.parent.mkdir(parents=True, exist_ok=True)

        if dst.exists():
            if dst.read_text() != content:
                if not dry_run:
                    dst.write_text(content)
                report.add(fpath, "updated")
            else:
                report.add(fpath, "unchanged")
        else:
            if not dry_run:
                dst.write_text(content)
            report.add(fpath, "added")


def sync_public_repo(
    source_root: Path,
    public_root: Path,
    dry_run: bool = True,
    auto_commit: bool = False,
) -> SyncReport:
    """
    Run a full incremental sync from private → public repo.

    Args:
        source_root: Private repo root
        public_root: Public repo root (must already be a git repo)
        dry_run: If True, only preview changes
        auto_commit: If True, git add + commit after applying
    """
    report = SyncReport()
    mode = "DRY RUN" if dry_run else "APPLY"

    print(f"\n{'═' * 60}")
    print(f"  Syncing Public Repository [{mode}]")
    print(f"  Source:  {source_root}")
    print(f"  Target:  {public_root}")
    print(f"{'═' * 60}\n")

    # 1. Cards
    print("📇 Syncing AVE cards...")
    card_count = sync_cards(source_root, public_root, report, dry_run)
    print(f"  → {card_count} cards processed")

    # 2. Indexes
    print("\n📊 Syncing database indexes...")
    sync_indexes(public_root, report, dry_run)

    # 3. Toolkit
    print("\n📦 Syncing AVE toolkit...")
    sync_toolkit(source_root, public_root, report, dry_run)

    # 4. Community docs
    print("\n📋 Syncing community docs...")
    sync_community_docs(source_root, public_root, report, dry_run)

    # 5. GitHub infrastructure
    print("\n🔧 Syncing GitHub infrastructure...")
    sync_github_infra(source_root, public_root, report, dry_run)

    # Summary
    print(report.summary())

    if dry_run and report.has_changes:
        print("\n  💡 Run with --apply to write these changes.")
        print("  💡 Run with --apply --commit to also git commit.\n")

    # Auto-commit
    if not dry_run and auto_commit and report.has_changes:
        import subprocess

        now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        n_changes = len(report.added) + len(report.updated)
        msg = f"sync: update {n_changes} files from private repo ({now})"

        print(f"\n🔀 Committing: {msg}")
        subprocess.run(["git", "add", "-A"], cwd=public_root, check=True)
        subprocess.run(
            ["git", "commit", "-m", msg],
            cwd=public_root,
            check=True,
        )
        print("  ✓ Committed. Push with: cd public-repo && git push origin main")

    return report


def main():
    parser = argparse.ArgumentParser(
        description="Incrementally sync private AVE data to the public repo.",
    )
    parser.add_argument(
        "--public-repo",
        default="public-repo",
        help="Path to the public repo (default: public-repo/)",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Actually write changes (default is dry-run)",
    )
    parser.add_argument(
        "--commit",
        action="store_true",
        help="Auto-commit after applying (requires --apply)",
    )
    args = parser.parse_args()

    source_root = PROJECT_ROOT
    public_root = Path(args.public_repo)
    if not public_root.is_absolute():
        public_root = PROJECT_ROOT / public_root

    if not (public_root / ".git").is_dir():
        print(f"❌ {public_root} is not a git repository.")
        print("   Use export_public_repo.py for initial generation.")
        sys.exit(1)

    sync_public_repo(
        source_root=source_root,
        public_root=public_root,
        dry_run=not args.apply,
        auto_commit=args.commit,
    )


if __name__ == "__main__":
    main()
