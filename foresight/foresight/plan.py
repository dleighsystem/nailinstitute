"""Plan + Step datamodel."""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class Step:
    """One planned tool call. ``args`` are kwargs for the tool."""
    tool: str
    args: dict[str, Any] = field(default_factory=dict)
    rationale: str = ""

    def to_dict(self) -> dict:
        return {"tool": self.tool, "args": dict(self.args),
                "rationale": self.rationale}

    @classmethod
    def from_dict(cls, d: dict) -> "Step":
        return cls(tool=str(d["tool"]),
                   args=dict(d.get("args") or {}),
                   rationale=str(d.get("rationale", "")))


@dataclass
class Plan:
    """A multi-step proposal generated by the agent before execution."""
    goal: str
    steps: list[Step] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)

    # ── lifecycle ───────────────────────────────────────────────
    def __len__(self) -> int: return len(self.steps)

    def tools(self) -> list[str]:
        return [s.tool for s in self.steps]

    def to_dict(self) -> dict:
        return {
            "goal": self.goal,
            "steps": [s.to_dict() for s in self.steps],
            "metadata": dict(self.metadata),
        }

    @classmethod
    def from_dict(cls, d: dict) -> "Plan":
        return cls(
            goal=str(d.get("goal", "")),
            steps=[Step.from_dict(s) for s in d.get("steps", [])],
            metadata=dict(d.get("metadata") or {}),
        )

    # ── persistence ──────────────────────────────────────────────
    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)

    @classmethod
    def from_json(cls, s: str) -> "Plan":
        return cls.from_dict(json.loads(s))

    @classmethod
    def from_path(cls, p: Path | str) -> "Plan":
        return cls.from_json(Path(p).read_text())

    # ── prompt-friendly serialisation ────────────────────────────
    def render(self) -> str:
        """Compact human/LLM-readable form."""
        lines = [f"GOAL: {self.goal}", "STEPS:"]
        for i, s in enumerate(self.steps, 1):
            args_repr = ", ".join(f"{k}={v!r}" for k, v in s.args.items())
            lines.append(f"  {i}. {s.tool}({args_repr})")
            if s.rationale:
                lines.append(f"       why: {s.rationale}")
        return "\n".join(lines)
